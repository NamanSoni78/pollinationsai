import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { PollinationsIdentity } from "../../pollinations-byop-proxy/src/index";

const DEFAULT_GITIGNORE = `# Auto-generated by Agent Ground Autonomous Git Engine
.env
.env.*
!.env.example
*.pem
*.key
secrets.vars.json
node_modules/
dist/
build/
.agent/logs/
.playwright-cli/
`;

/**
 * Secret-leak patterns blocked before any autonomous commit is allowed.
 */
const SECRET_PATTERNS: Array<{ name: string; regex: RegExp }> = [
  { name: "Pollinations Secret Key", regex: /\bsk_[A-Za-z0-9]{16,}\b/ },
  { name: "GitHub Fine-Grained PAT", regex: /\bgithub_pat_[A-Za-z0-9_]{20,}\b/ },
  { name: "GitHub Classic PAT", regex: /\bghp_[A-Za-z0-9]{20,}\b/ },
  { name: "OpenAI Secret Key", regex: /\bsk-proj-[A-Za-z0-9_-]{20,}\b/ },
  { name: "Private Key Block", regex: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/ },
  { name: "Cloudflare API Token Assignment", regex: /CLOUDFLARE_API_TOKEN\s*=\s*["']?[A-Za-z0-9_-]{20,}/ },
  { name: "EdgeOne API Token Assignment", regex: /EDGEONE_API_TOKEN\s*=\s*["']?[A-Za-z0-9_-]{20,}/ },
];

export class SecretLeakDetectedError extends Error {
  readonly findings: Array<{ file: string; pattern: string }>;

  constructor(findings: Array<{ file: string; pattern: string }>) {
    super(
      `Pre-commit secret-leak guard blocked commit! Detected ${findings.length} potential secret(s): ${findings.map((f) => `${f.file} (${f.pattern})`).join(", ")}`,
    );
    this.name = "SecretLeakDetectedError";
    this.findings = findings;
  }
}

export function scanContentForSecrets(
  file: string,
  content: string,
): Array<{ file: string; pattern: string }> {
  if (file.endsWith(".env.example")) return [];
  const findings: Array<{ file: string; pattern: string }> = [];
  for (const rule of SECRET_PATTERNS) {
    if (rule.regex.test(content)) {
      findings.push({ file, pattern: rule.name });
    }
  }
  return findings;
}

/**
 * Per-VM Autonomous Git Engine (Issue #20357 §3.D).
 * - Initializes local Git repo with Pollinations user.name & user.email
 * - Auto-generates `.gitignore`
 * - Isolates each agent to `agent/<agent_id>/<task>` branch
 * - Enforces pre-commit secret-leak scan
 * - Supports `git_checkpoint`, `git_branch_experiment`, and `git_rollback`
 */
export class AutonomousGitEngine {
  constructor(
    private readonly repoDir: string,
    private readonly agentId: string,
  ) {}

  private git(args: string[]): string {
    return execFileSync("git", args, {
      cwd: this.repoDir,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }).trim();
  }

  initRepo(identity: Pick<PollinationsIdentity, "displayName" | "githubUsername" | "email">, taskSlug = "main-task"): {
    branch: string;
    gitignoreCreated: boolean;
  } {
    if (!existsSync(join(this.repoDir, ".git"))) {
      this.git(["init", "-q"]);
    }
    this.git(["config", "user.name", identity.displayName || identity.githubUsername]);
    this.git(["config", "user.email", identity.email]);

    const gitignorePath = join(this.repoDir, ".gitignore");
    let gitignoreCreated = false;
    if (!existsSync(gitignorePath)) {
      writeFileSync(gitignorePath, DEFAULT_GITIGNORE, "utf8");
      gitignoreCreated = true;
    }

    // Ensure initial commit exists before creating isolated agent branch
    let hasCommits = true;
    try {
      this.git(["rev-parse", "--verify", "HEAD"]);
    } catch {
      hasCommits = false;
    }
    if (!hasCommits) {
      this.git(["add", ".gitignore"]);
      this.git(["commit", "-q", "-m", "chore: initialize autonomous VM workspace"]);
    }

    const safeSlug = taskSlug.toLowerCase().replace(/[^a-z0-9-]+/g, "-").slice(0, 32) || "work";
    const branch = `agent/${this.agentId}/${safeSlug}`;
    const existingBranches = this.git(["branch", "--list", branch]);
    if (!existingBranches) {
      this.git(["checkout", "-q", "-b", branch]);
    } else {
      this.git(["checkout", "-q", branch]);
    }

    return { branch, gitignoreCreated };
  }

  /**
   * Scans staged/modified files for credentials before allowing any commit.
   */
  verifyNoSecretLeaks(): void {
    const statusOut = this.git(["status", "--porcelain"]);
    if (!statusOut) return;

    const findings: Array<{ file: string; pattern: string }> = [];
    for (const line of statusOut.split("\n")) {
      if (!line.trim()) continue;
      const statusCode = line.slice(0, 2);
      if (statusCode.includes("D")) continue;
      const relFile = line.slice(3).trim().replace(/^"|"$/g, "");
      const fullPath = join(this.repoDir, relFile);
      if (!existsSync(fullPath)) continue;
      try {
        const content = readFileSync(fullPath, "utf8");
        findings.push(...scanContentForSecrets(relFile, content));
      } catch {
        // Ignore binary/unreadable files
      }
    }

    if (findings.length > 0) {
      throw new SecretLeakDetectedError(findings);
    }
  }

  git_checkpoint(params: { message: string; milestone_id?: string }): {
    sha: string;
    branch: string;
    changed: boolean;
  } {
    this.verifyNoSecretLeaks();
    this.git(["add", "-A"]);

    const staged = this.git(["diff", "--cached", "--name-only"]);
    const branch = this.git(["rev-parse", "--abbrev-ref", "HEAD"]);
    if (!staged) {
      const sha = this.git(["rev-parse", "HEAD"]);
      return { sha, branch, changed: false };
    }

    const fullMsg = params.milestone_id
      ? `[${params.milestone_id}] ${params.message}`
      : params.message;
    this.git(["commit", "-q", "-m", fullMsg]);
    const sha = this.git(["rev-parse", "HEAD"]);
    return { sha, branch, changed: true };
  }

  git_branch_experiment(params: { name: string }): { branch: string } {
    const slug = params.name.toLowerCase().replace(/[^a-z0-9-]+/g, "-").slice(0, 40);
    const branch = `agent/${this.agentId}/exp-${slug}`;
    this.git(["checkout", "-q", "-b", branch]);
    return { branch };
  }

  git_rollback(params: { target_sha_or_tag: string; reason: string }): {
    restored_sha: string;
    reason: string;
  } {
    this.git(["reset", "--hard", "-q", params.target_sha_or_tag]);
    const restored_sha = this.git(["rev-parse", "HEAD"]);
    return { restored_sha, reason: params.reason };
  }

  getTelemetry(): { branch: string; statusSummary: string; recentCommits: string[]; headSha: string } {
    try {
      const branch = this.git(["rev-parse", "--abbrev-ref", "HEAD"]);
      const headSha = this.git(["rev-parse", "--short", "HEAD"]);
      const porcelain = this.git(["status", "--porcelain"]);
      const statusSummary = porcelain
        ? `${porcelain.split("\n").length} modified/untracked file(s)`
        : "clean working tree";
      const logOut = this.git(["log", "-n", "5", "--oneline"]);
      const recentCommits = logOut ? logOut.split("\n") : [];
      return { branch, statusSummary, recentCommits, headSha };
    } catch {
      return {
        branch: `agent/${this.agentId}/uninitialized`,
        statusSummary: "not initialized",
        recentCommits: [],
        headSha: "0000000",
      };
    }
  }
}
